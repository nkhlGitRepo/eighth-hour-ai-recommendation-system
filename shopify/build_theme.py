#!/usr/bin/env python3
"""
Assemble the MyStyle working-copy theme.

    python3 shopify/build_theme.py            # build shopify/private/theme-build
    python3 shopify/build_theme.py --check    # check every edit still applies; write nothing

The result is the brand's theme exactly as downloaded (shopify/private/theme-original),
plus:
  * the MyStyle files in shopify/theme/ (sections, snippets, assets, templates);
  * two private snippets that never enter this public repository -- the theme
    secret (from shopify/private/secrets.env) and the launch data
    (shopify/private/mystyle-launch-data.liquid);
  * snippets/mystyle-size-guide.liquid, generated here from the engine's own size
    chart, so the size drawer and the engine can never disagree;
  * six small edits to the brand's files, each anchored on text that must
    appear exactly once -- if the brand's theme changes underneath, the build
    stops rather than guessing.

It writes shopify/private/theme-build/.mystyle-files listing every file it added
or changed, for `shopify theme push --only` (see shopify/README.md). It never
talks to Shopify itself.
"""

import argparse
import json
import re
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
PRIVATE = HERE / "private"
ORIGINAL = PRIVATE / "theme-original"
BUILD = PRIVATE / "theme-build"
OURS = HERE / "theme"

sys.path.insert(0, str(REPO / "backend"))
from py_src.constants import SIZE_CHART_SOURCE, STANDARD_SIZES  # noqa: E402

# US and UK equivalents in Eighth Hour's October 2026 size guide (the brand's
# "0. Size Guide" sheet, tab "updated oct '26"). Measurements come from the
# engine's SIZE_CHART_SOURCE, the single source of truth for those.
US_UK = {
    "XXS": ("0-2", "4-6"), "XS": ("4-6", "8-10"), "S": ("8-10", "12-14"),
    "M": ("12-14", "16-18"), "L": ("16-18", "20-22"), "XL": ("20-22", "24-26"),
    "XXL": ("24-26", "28-30"),
}
TABLES = {
    "tops": ("bust", "waist"),
    "bottoms": ("waist", "hips"),
    "all": ("bust", "waist", "hips"),
}


def _cm(value):
    return f"{value:g}"


def _inches(value_cm):
    """The guide's own inch figures: centimetres to the nearest half inch."""
    halves = round(value_cm / 2.54 * 2)
    whole, half = divmod(halves, 2)
    return f"{whole}{'½' if half else ''}"


def size_guide_snippet() -> str:
    def rows(dimensions, unit):
        out = []
        for size in STANDARD_SIZES:
            us, uk = US_UK[size]
            cells = [size, us, uk]
            for d in dimensions:
                low, high = SIZE_CHART_SOURCE[size][d]
                cells.append(f"{_cm(low)}–{_cm(high)}" if unit == "cm" else f"{_inches(low)}–{_inches(high)}")
            style = ' style="display:none"' if unit == "cm" else ""
            out.append(f'<tr class="sizeWgt-{unit} sizeWgt-data"{style}>' + "".join(f"<td>{c}</td>" for c in cells) + "</tr>")
        return "\n".join(out)

    tables = []
    for kind, dimensions in TABLES.items():
        heads = ["Our Size", "US", "UK"] + [d.capitalize() for d in dimensions]
        tables.append(
            f"{{%- {'if' if not tables else 'elsif'} mystyle_kind == '{kind}' -%}}\n"
            + "<thead><tr>" + "".join(f"<th>{h}</th>" for h in heads) + "</tr></thead>\n<tbody>\n"
            + rows(dimensions, "cm") + "\n" + rows(dimensions, "in") + "\n</tbody>"
        )
    return (
        "{%- comment -%}\n"
        "  MyStyle: Eighth Hour's October 2026 size guide for the size drawer.\n"
        "  GENERATED by shopify/build_theme.py from the engine's SIZE_CHART_SOURCE --\n"
        "  edit that, not this. Replaces the per-product custom.size_chart fields in\n"
        "  this theme only (those are shared with the live theme, so they stay as they are).\n"
        "  Which table: from the product's SKU (TOP/VST/JKT tops, PNT/SKR bottoms), else\n"
        "  from the product or collection title; dresses and anything else get all three.\n"
        "  Usage: {% render 'mystyle-size-guide', size_widget: size_widget %}\n"
        "{%- endcomment -%}\n"
        "{%- liquid\n"
        "  assign mystyle_kind = 'all'\n"
        "  assign mystyle_sku = ''\n"
        "  if size_widget.variants\n"
        "    assign mystyle_sku = size_widget.variants.first.sku | upcase\n"
        "  endif\n"
        "  assign mystyle_title = size_widget.title | downcase\n"
        "  if mystyle_sku contains '-TOP-' or mystyle_sku contains '-VST-' or mystyle_sku contains '-JKT-'\n"
        "    assign mystyle_kind = 'tops'\n"
        "  elsif mystyle_sku contains '-PNT-' or mystyle_sku contains '-SKR-'\n"
        "    assign mystyle_kind = 'bottoms'\n"
        "  elsif mystyle_sku contains '-DRS-'\n"
        "    assign mystyle_kind = 'all'\n"
        "  elsif mystyle_title contains 'dress'\n"
        "    assign mystyle_kind = 'all'\n"
        "  elsif mystyle_title contains 'top' or mystyle_title contains 'vest' or mystyle_title contains 'jacket' or mystyle_title contains 'shirt' or mystyle_title contains 'blouse'\n"
        "    assign mystyle_kind = 'tops'\n"
        "  elsif mystyle_title contains 'bottom' or mystyle_title contains 'skirt' or mystyle_title contains 'trouser' or mystyle_title contains 'pant'\n"
        "    assign mystyle_kind = 'bottoms'\n"
        "  endif\n"
        "-%}\n"
        '<div class="unit-toggle"><span class="unit-btn " data-unit="cm">cm</span><span class="unit-btn active" data-unit="in">in</span></div>\n'
        '<table class="size-table">\n'
        + "\n".join(tables) + "\n{%- endif -%}\n"
        "</table>\n"
        '<p class="note">Fit varies with each style. Choose what feels right for you.</p>\n'
    )


def _patch(root: Path, rel: str, anchor: str, replacement: str):
    path = root / rel
    text = path.read_text()
    count = text.count(anchor)
    if count != 1:
        raise SystemExit(f"{rel}: expected the anchor once, found it {count} times:\n{anchor!r}\n"
                         "The brand's theme changed -- update the edit in shopify/build_theme.py.")
    path.write_text(text.replace(anchor, replacement))


def _edit_index_json(path: Path):
    """Add the My Style picks section after the home page's category list."""
    text = path.read_text()
    header = ""
    if text.lstrip().startswith("/*"):
        end = text.index("*/") + 2
        header, text = text[:end] + "\n", text[end:]
    data = json.loads(text)
    anchor = "collection_list_BYFgK8"
    if anchor not in data["order"]:
        raise SystemExit("templates/index.json: the category list section moved -- update shopify/build_theme.py")
    data["sections"]["mystyle_picks"] = {
        "type": "mystyle-picks",
        "settings": {"heading": "Picked for you", "heading_size": "h1", "count": 4},
    }
    order = data["order"]
    order.insert(order.index(anchor) + 1, "mystyle_picks")
    path.write_text(header + json.dumps(data, indent=2) + "\n")


EDITS = [
    ("layout/theme.liquid", "  </head>",
     "    {%- comment -%} MyStyle: keep its pages out of search results {%- endcomment -%}\n"
     "    {%- if template.suffix == 'mystyle' or template.suffix == 'mystyle-token' -%}<meta name=\"robots\" content=\"noindex\">{%- endif -%}\n"
     "  </head>"),
    ("layout/theme.liquid", "  </body>",
     "    {%- comment -%} MyStyle: settings and script, on the pages that use it {%- endcomment -%}\n"
     "    {%- if template.name == 'product' or template.name == 'index' or template.suffix == 'mystyle' -%}{%- render 'mystyle-config' -%}{%- endif -%}\n"
     "  </body>"),
    ("sections/main-product.liquid",
     "{% render 'product-variant-picker', product: product, block: block, product_form_id: product_form_id %}\n",
     "{% render 'product-variant-picker', product: product, block: block, product_form_id: product_form_id %}\n"
     "                {% render 'mystyle-find-my-size', product: product %}\n"),
    ("snippets/header-dropdown-menu.liquid", "    {%- endfor -%}\n  </ul>\n</nav>",
     "    {%- endfor -%}\n    {%- render 'mystyle-nav-link', variant: 'desktop' -%}\n  </ul>\n</nav>"),
    ("snippets/header-drawer.liquid", "              {%- endfor -%}\n            </ul>\n          </nav>",
     "              {%- endfor -%}\n              {%- render 'mystyle-nav-link', variant: 'drawer' -%}\n            </ul>\n          </nav>"),
]


def _edit_size_widget(path: Path):
    text = path.read_text()
    pattern = re.compile(r'<div class="unit-toggle">.*?<p class="note">Fit varies with each style\. Choose what feels right for you\.</p>', re.S)
    if len(pattern.findall(text)) != 1:
        raise SystemExit("sections/size-widget.liquid: the size table changed -- update shopify/build_theme.py")
    path.write_text(pattern.sub("{%- render 'mystyle-size-guide', size_widget: size_widget -%}", text))


def _theme_secret() -> str:
    env = PRIVATE / "secrets.env"
    for line in env.read_text().splitlines():
        if line.startswith("MYSTYLE_THEME_SECRET="):
            value = line.split("=", 1)[1].strip()
            if value:
                return value
    raise SystemExit(f"{env}: no MYSTYLE_THEME_SECRET")


def build(check_only: bool):
    if not ORIGINAL.is_dir():
        raise SystemExit(f"{ORIGINAL} missing -- pull the working-copy theme first (shopify/README.md)")
    target = BUILD if not check_only else PRIVATE / "theme-check"
    if target.exists():
        shutil.rmtree(target)
    shutil.copytree(ORIGINAL, target, ignore=shutil.ignore_patterns(".shopify", ".mystyle-files"))

    changed = set()
    for source in OURS.rglob("*"):
        if source.is_file():
            rel = source.relative_to(OURS)
            (target / rel).parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, target / rel)
            changed.add(str(rel))

    secret_snippet = target / "snippets" / "mystyle-secret.liquid"
    secret_snippet.write_text(_theme_secret())
    shutil.copy2(PRIVATE / "mystyle-launch-data.liquid", target / "snippets" / "mystyle-launch-data.liquid")
    (target / "snippets" / "mystyle-size-guide.liquid").write_text(size_guide_snippet())
    changed |= {"snippets/mystyle-secret.liquid", "snippets/mystyle-launch-data.liquid", "snippets/mystyle-size-guide.liquid"}

    for rel, anchor, replacement in EDITS:
        _patch(target, rel, anchor, replacement)
        changed.add(rel)
    _edit_size_widget(target / "sections" / "size-widget.liquid")
    _edit_index_json(target / "templates" / "index.json")
    changed |= {"sections/size-widget.liquid", "templates/index.json"}

    if check_only:
        shutil.rmtree(target)
        print(f"All {len(EDITS) + 2} edits apply cleanly.")
        return
    (target / ".mystyle-files").write_text("\n".join(sorted(changed)) + "\n")
    print(f"Built {target.relative_to(REPO)}: {len(changed)} files added or changed:")
    for rel in sorted(changed):
        print("  ", rel)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="check the edits apply; write nothing")
    build(parser.parse_args().check)
